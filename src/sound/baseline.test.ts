/**
 * With no patch and no declared kit, the synth must render what it always
 * did. These loudness fingerprints of the output samples were taken from the
 * code before patches existed (at a956a73); a change to them changes how the
 * shipped apps sound. They are compared with a tolerance, not bit for bit: the
 * last bits of a float differ between CPUs, and nobody hears them.
 */
import assert from "node:assert/strict";
import { test } from "node:test";
import { type Stereo, stereo } from "./dsp.js";
import { renderSynthNote } from "./synth.js";
import type { ScoreNote } from "./types.js";

const SR = 24000;

/** RMS of each half of each channel, to 4 places; a coarse picture of the loudness over time. */
function digest(parts: Stereo[]): string {
  const rms = (x: Float32Array) => {
    let e = 0;
    for (let i = 0; i < x.length; i++) e += x[i]! * x[i]!;
    return Math.sqrt(e / Math.max(1, x.length)).toFixed(4);
  };
  const out: string[] = [];
  for (const s of parts) {
    for (const ch of [s.l, s.r]) {
      const h = ch.length >> 1;
      out.push(rms(ch.subarray(0, h)), rms(ch.subarray(h)));
    }
  }
  return out.join(",");
}

/** Equal but for rounding: the same fingerprints, each number within a hair of the other. */
function assertClose(now: Record<string, string> | string[], want: Record<string, string> | string[]): void {
  const keys = Object.keys(want);
  assert.deepEqual(Object.keys(now), keys);
  for (const k of keys) {
    const a = (now as Record<string, string>)[k]!.split(",").map(Number);
    const b = (want as Record<string, string>)[k]!.split(",").map(Number);
    assert.equal(a.length, b.length, k);
    a.forEach((v, i) => assert.ok(Math.abs(v - b[i]!) <= 5e-4, `${k}[${i}]: ${v} vs ${b[i]}`));
  }
}

/** A plain note, a legato note touching it (a glide), a slide and a swell, with and without touch. */
function program(p: number): string {
  const note = (t: number, dur: number, key: number, vel: number, more: Partial<ScoreNote> = {}): ScoreNote => ({ t, dur, key, vel, ch: 0, role: "lead", program: p, ...more });
  const notes = [
    note(0.1, 0.4, 48, 100, { legato: true }),
    note(0.5, 0.5, 55, 70, { legato: true }),
    note(1.2, 0.3, 72, 120, { gesture: "slide", curves: { bend: [[0, -2], [0.1, 0]] } }),
    note(1.8, 0.5, 60, 50, { gesture: "swell", curves: { level: [[0, 0.5], [0.3, 1]] } }),
  ];
  return digest(
    [false, true].map((touch) => {
      const out = stereo(SR * 4);
      notes.forEach((n, i) => renderSynthNote(out, n, SR, "retro", notes[i - 1], touch));
      return out;
    }),
  );
}

